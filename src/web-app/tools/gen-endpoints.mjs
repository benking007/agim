#!/usr/bin/env node
/**
 * gen-endpoints.mjs — emit src/lib/api/endpoints.ts from
 * tools/endpoints.json.
 *
 * The output is intentionally minimal: each backend route becomes a
 * single thin function that delegates to `client.get/post/...`. The
 * caller passes `{ query, body }`; the function returns the typed
 * response. Type assignments live in types/api.ts and are added
 * incrementally — anything we haven't typed yet returns `unknown` so
 * TS forces consumers to acknowledge they're using a loose response.
 *
 * Run after every change to tools/endpoints.json:
 *   node tools/gen-endpoints.mjs
 *
 * The output is checked into git (it's the source of truth for the
 * hooks layer); generating at build time would be neat but it adds
 * a step to every CI run and makes diff-review harder.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const IN = resolve(__dirname, 'endpoints.json')
const OUT = resolve(__dirname, '../src/lib/api/endpoints.ts')

const { endpoints } = JSON.parse(readFileSync(IN, 'utf-8'))

// Map endpoint name → request/response types from types/api.ts.
// Routes not present in this table default to (unknown, unknown).
// Add more mappings here as new pages get typed; the unmapped ones
// keep working with `unknown`, just without type safety.
const TYPE_MAP = {
  // Auth
  login:               { body: 'LoginBody',          response: 'LoginResponse' },
  logout:              { response: 'OkResponse' },

  // Jobs
  listJobs:            { query: 'ListJobsQuery',     response: 'ListJobsResponse' },
  createJob:           { body:  'CreateJobBody',     response: 'CreateJobResponse' },
  batchRunJobs:        { body:  'BatchJobBody',      response: 'OkResponse' },
  batchCancelJobs:     { body:  'BatchJobBody',      response: 'OkResponse' },

  // Schedules
  listSchedules:       { response: 'ListSchedulesResponse' },

  // Reminders
  listReminders:       { query: 'ListRemindersQuery', response: 'ListRemindersResponse' },

  // Memos
  listMemos:           { query: 'ListMemosQuery',    response: 'ListMemosResponse' },

  // Approvals
  listApprovals:       { response: 'ListApprovalsResponse' },

  // Memory
  listMemoryUsers:     { response: '{ users: string[] }' },
  listMemoryFacts:     { query: 'ListMemoryFactsQuery', response: 'ListMemoryFactsResponse' },
  deleteMemoryFacts:   { query: '{ user_key: string; ids?: string }', response: 'OkResponse' },
  getMemoryPersona:    { query: '{ user_key: string }', response: 'Persona' },
  updateMemoryPersona: { query: '{ user_key: string }', body: 'UpdatePersonaBody', response: 'OkResponse' },
  deleteMemoryPersona: { query: '{ user_key: string }', response: 'OkResponse' },
  getMemoryVectorStatus: { query: '{ user_key?: string }', response: 'VectorStatus' },

  // Config
  getConfig:           { response: 'AppConfig' },

  // Health / observability
  getHealth:           { response: '{ status: string }' },
  getHealthSummary:    { query: '{ days?: number }', response: 'HealthSummary' },
  getHealthTopN:       { query: '{ dim: "user"|"agent"|"platform"; by: "calls"|"cost"|"errors"|"avg_latency"; days?: number; limit?: number }', response: 'TopNResponse' },
}

function camelToPathFn(name) {
  return name
}

function tsType(t) {
  return t ?? 'unknown'
}

// Collect just the types actually referenced by TYPE_MAP so we don't
// emit dead imports that trip `noUnusedLocals`. Anything that contains
// an identifier matching /^[A-Z][A-Za-z0-9_]*$/ counts.
const TS_IDENT = /\b[A-Z][A-Za-z0-9_]*\b/g
const usedTypes = new Set()
for (const t of Object.values(TYPE_MAP)) {
  for (const v of Object.values(t)) {
    if (typeof v !== 'string') continue
    for (const m of v.matchAll(TS_IDENT)) {
      usedTypes.add(m[0])
    }
  }
}
// Filter to those that actually exist in types/api.ts so inline type
// expressions like `Record<string, string>` don't leak in. Maintainers
// keep this list in sync with types/api.ts exports.
const KNOWN_API_TYPES = new Set([
  'AppConfig', 'Approval', 'ApiError', 'BatchJobBody', 'CreateJobBody',
  'CreateJobResponse', 'Fact', 'FactCategory', 'HealthSummary', 'Job',
  'JobKind', 'JobStatus', 'ListApprovalsResponse', 'ListJobsQuery',
  'ListJobsResponse', 'ListMemoryFactsQuery', 'ListMemoryFactsResponse',
  'ListMemosQuery', 'ListMemosResponse', 'ListRemindersQuery',
  'ListRemindersResponse', 'ListSchedulesResponse', 'LoginBody',
  'LoginResponse', 'Memo', 'OkResponse', 'PageQuery', 'Persona',
  'Reminder', 'ReminderStatus', 'ResolveApprovalBody', 'Schedule',
  'SnoozeReminderBody', 'SnoozeReminderResponse', 'TopNResponse',
  'TopNRow', 'UpdatePersonaBody', 'VectorStatus',
])
const importList = [...usedTypes].filter((t) => KNOWN_API_TYPES.has(t)).sort()

const lines = []
lines.push('/* eslint-disable */')
lines.push('/**')
lines.push(' * GENERATED by tools/gen-endpoints.mjs — DO NOT EDIT BY HAND.')
lines.push(' * Source: tools/endpoints.json (regenerate with')
lines.push(' *         `node tools/extract-endpoints.mjs && node tools/gen-endpoints.mjs`).')
lines.push(' *')
lines.push(' * One thin function per backend REST endpoint. Functions live on the')
lines.push(' * exported `api` object so consumers `import { api } from "@/lib/api/endpoints"`')
lines.push(' * and call `api.listJobs(...)`. Hooks in src/hooks/ wrap these in')
lines.push(' * react-query useQuery / useMutation. The wrapper itself is in')
lines.push(' * lib/api/client.ts and centralizes auth + error handling.')
lines.push(' */')
lines.push('')
lines.push("import { client } from './client'")
if (importList.length > 0) {
  lines.push('import type {')
  for (const t of importList) lines.push(`  ${t},`)
  lines.push("} from '@/types/api'")
}
lines.push('')
lines.push('export const api = {')

for (const ep of endpoints) {
  const t = TYPE_MAP[ep.name] ?? {}
  const queryT = tsType(t.query)
  const bodyT  = tsType(t.body)
  const respT  = tsType(t.response)
  const hasParam = ep.path.includes('/:')
  const pathStr = hasParam
    ? '`' + ep.path.replace(/:(\w+)/g, '${${$1}}').replace(/\$\{\$\{(\w+)\}\}/g, '${$1}') + '`'
    : `'${ep.path}'`

  const sig = []
  if (hasParam) {
    const params = [...ep.path.matchAll(/:(\w+)/g)].map((m) => m[1])
    for (const p of params) sig.push(`${p}: string | number`)
  }
  if (t.query) sig.push(`query: ${queryT}`)
  if (t.body)  sig.push(`body: ${bodyT}`)
  if (!t.query && !t.body && (ep.method === 'GET' || ep.method === 'DELETE')) {
    // No query type but caller might still want to pass arbitrary
    // query — accept an optional pass-through.
    sig.push(`opts?: { query?: Record<string, string | number | boolean | undefined> }`)
  }
  if (!t.body && !t.query && ep.method !== 'GET' && ep.method !== 'DELETE') {
    sig.push(`opts?: { body?: unknown }`)
  }

  const optsBuild = []
  if (t.query) optsBuild.push('query')
  if (t.body)  optsBuild.push('body')
  let optsExpr = ''
  if (optsBuild.length === 1) {
    optsExpr = `{ ${optsBuild[0]} }`
  } else if (optsBuild.length > 1) {
    optsExpr = `{ ${optsBuild.join(', ')} }`
  } else if (!t.query && !t.body) {
    optsExpr = 'opts'
  }

  const verb = ep.method.toLowerCase()
  const sigStr = sig.length ? `(${sig.join(', ')})` : '()'
  const callArgs = optsExpr ? `(${pathStr}, ${optsExpr})` : `(${pathStr})`

  lines.push(`  /** ${ep.method} ${ep.path}${ep.authRequired ? '' : ' (public)'} */`)
  lines.push(`  ${ep.name}: ${sigStr} =>`)
  lines.push(`    client.${verb}<${respT}>${callArgs},`)
  lines.push('')
}
lines.push('} as const')
lines.push('')

writeFileSync(OUT, lines.join('\n'))
console.log(`Wrote ${endpoints.length} endpoints to ${OUT.split('/').slice(-5).join('/')}`)
