const dicts: Record<Lang, Record<string, string>> = { en, zh }

/** Translate. If `key` is missing in `lang`, falls back to en, then to the key itself. */
export function t(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  let s: string = dicts[lang]?.[key] ?? en[key] ?? key
  for (const [k, v] of Object.entries(vars)) {
    s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
  }
  return s
}

/** Read persisted preference; returns null when not set. */
export function readSavedLang(): Lang | null {
  try {
    const raw = readFileSync(PREF_FILE, 'utf-8').trim()
    if (raw === 'en' || raw === 'zh') return raw
  } catch { /* not set */ }
  return null
}

/** Persist to ~/.agim/cli-lang. Best-effort — failures only logged. */
export function saveLang(lang: Lang): void {
  try {
    mkdirSync(dirname(PREF_FILE), { recursive: true })
    writeFileSync(PREF_FILE, `${lang}\n`, { mode: 0o644 })
  } catch (err) {
    console.warn(`⚠️ Could not save language preference: ${err instanceof Error ? err.message : String(err)}`)
  }
}



/** Localized install hints for missing agents at `agim start`. */
export function formatAgentInstallHint(lang: Lang, missing: string[]): string {
  if (missing.length === 0) return ''
  const hintFor = (name: string): string => {
    const key = `agents.install_hint.${name.replace(/-/g, '_')}` as Key
    if (key in en) return t(lang, key)
    const pkg = {
      'claude-code': 'npm i -g @anthropic-ai/claude-code',
      codex: 'npm i -g @openai/codex',
      copilot: 'npm i -g @github/copilot',
      opencode: 'npm i -g opencode-ai',
      antigravity: 'curl -fsSL https://antigravity.google/cli/install.sh | bash',
      qoder: 'curl -fsSL https://qoder.com/install | sh',
      pi: 'npm install -g @earendil-works/pi-coding-agent',
      mimo: 'curl -fsSL https://mimo.xiaomi.com/install | bash  # or: npm install -g @mimo-ai/cli',
      native: t(lang, 'agents.install_hint.native'),
    } as Record<string, string>
    return pkg[name] ?? `npm i -g ${name}`
  }
  if (missing.length === 1) {
    const agent = missing[0]
    if (!agent) return ''
    return t(lang, 'start.agents_install_one', { agent, hint: hintFor(agent) })
  }
  const lines = missing.map((agent) => t(lang, 'start.agents_install_line', { agent, hint: hintFor(agent) }))
  return `${t(lang, 'start.agents_install_header')}\n${lines.join('\n')}`
}

export function detectLangFromEnv(): Lang | null {
  const env = process.env.LC_ALL || process.env.LANG || process.env.LC_MESSAGES || ''
  const head = env.split('.')[0]?.replace('_', '-').toLowerCase() ?? ''
  if (head.startsWith('zh')) return 'zh'
  if (head.startsWith('en')) return 'en'
  return null
}

export function resolveCliLang(): Lang {
  return readSavedLang() ?? detectLangFromEnv() ?? 'en'
}

/** Raw EN strings — tests assert this dict contains no CJK. */
export function enDictionaryEntries(): ReadonlyArray<readonly [string, string]> {
  return Object.entries(en)
}

